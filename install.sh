#!/usr/bin/env bash
# vs-labs-linux installer (Ubuntu 24.04 first; Fedora notes in README are untested).
#
#   ./install.sh [--root DIR] [--msvc-version 14.50] [--sdk-version 10.0.26100] [--no-msbuild]
#                [--userspace] [--no-msvc]
#
# What it does
#   1. checks wine, msitools, python3, unzip, git. If something is missing it prints the one apt command to run
#      (needs sudo), or with --userspace (automatic when sudo is unavailable) downloads the .deb files and
#      unpacks them under DIR/root without root rights.
#   2. clones msvc-wine (open source, https://github.com/mstorsjo/msvc-wine).
#   3. shows Microsoft's Visual Studio license link and asks YOU to type "yes". Nothing is downloaded from
#      Microsoft before that, and the answer is never given on your behalf. The compiler, linker, headers and
#      libraries come straight from Microsoft's servers to your disk. This repo never contains or
#      redistributes any Microsoft binary.
#   4. installs MSVC + Windows SDK (+ MSBuild and the C++ MSBuild targets unless --no-msbuild).
#   5. links vslab into ~/.local/bin and writes DIR/env.sh.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=${VSLAB_ROOT:-$HOME/.local/share/vslab}
MSVC_VERSION=""; SDK_VERSION=""; MSBUILD=yes; USERSPACE=auto; DO_MSVC=yes
while [ $# -gt 0 ]; do
  case $1 in
    --root) ROOT=$2; shift 2;;
    --msvc-version) MSVC_VERSION=$2; shift 2;;
    --sdk-version) SDK_VERSION=$2; shift 2;;
    --no-msbuild) MSBUILD=no; shift;;
    --userspace) USERSPACE=yes; shift;;
    --no-msvc) DO_MSVC=no; shift;;
    -h|--help) sed -n 2,20p "$0"; exit 0;;
    *) echo "unknown option $1" >&2; exit 2;;
  esac
done
mkdir -p "$ROOT"; ROOT=$(cd "$ROOT" && pwd)
say() { printf '\n== %s\n' "$*"; }

# ---------------------------------------------------------------- 1. host packages
say "Checking host packages (root dir: $ROOT)"
. /etc/os-release 2>/dev/null || true
echo "OS: ${PRETTY_NAME:-unknown}"
missing=()
have() { command -v "$1" >/dev/null 2>&1 || [ -x "$ROOT/root/usr/bin/$1" ]; }
have wine64 || have wine || missing+=(wine64)
have msiextract || missing+=(msitools)
have python3 || missing+=(python3)
have unzip || missing+=(unzip)
have git || missing+=(git)
have curl || have wget || missing+=(curl)

if [ ${#missing[@]} -gt 0 ]; then
  echo "missing: ${missing[*]}"
  CAN_SUDO=no; [ "$(id -u)" = 0 ] && CAN_SUDO=yes
  sudo -n true 2>/dev/null && CAN_SUDO=yes
  if [ "$USERSPACE" = auto ]; then [ "$CAN_SUDO" = yes ] && USERSPACE=no || USERSPACE=yes; fi
  APT_PKGS="wine64 libwine wine msitools python3 unzip git curl ca-certificates"
  if [ "$USERSPACE" = no ]; then
    echo "Run this once (it needs sudo), then run ./install.sh again:"
    echo "    sudo apt update && sudo apt install -y $APT_PKGS"
    if [ "$CAN_SUDO" = yes ]; then
      read -r -p "Run it now? [y/N] " a </dev/tty
      if [ "$a" = y ] || [ "$a" = Y ]; then sudo apt update && sudo apt install -y $APT_PKGS; else exit 1; fi
    else exit 1; fi
  else
    say "No sudo: unpacking the packages into $ROOT/root (user space, no root needed)"
    command -v apt-get >/dev/null || { echo "apt-get not found: this fallback is Debian/Ubuntu only"; exit 1; }
    mkdir -p "$ROOT/debs" "$ROOT/root"
    ( cd "$ROOT/debs"
      pk=$(apt-get -s install --no-install-recommends -o Debug::NoLocking=1 wine64 libwine msitools 2>/dev/null | awk '/^Inst /{print $2}')
      [ -n "$pk" ] || { echo "could not resolve packages (is 'apt update' recent?)"; exit 1; }
      # shellcheck disable=SC2086
      apt-get download $pk
      for d in *.deb; do dpkg -x "$d" "$ROOT/root"; done )
    echo "unpacked $(ls "$ROOT/debs" | wc -l) packages; you can delete $ROOT/debs afterwards"
  fi
fi

# ---------------------------------------------------------------- env.sh
if [ -d "$ROOT/root/usr/bin" ]; then
cat > "$ROOT/env.sh" <<EOF
# generated by vs-labs-linux install.sh (user-space Wine)
export VSLAB_ROOT=$ROOT
export PATH=$ROOT/root/usr/bin:$ROOT/root/usr/lib/wine:\$PATH
export LD_LIBRARY_PATH=$ROOT/root/usr/lib/x86_64-linux-gnu:\${LD_LIBRARY_PATH:-}
export WINEDLLPATH=$ROOT/root/usr/lib/x86_64-linux-gnu/wine
export WINEPREFIX=$ROOT/wineprefix
export WINEDEBUG=-all
export WINEARCH=win64
export DISPLAY=
export WINESERVER=$ROOT/root/usr/lib/wine/wineserver64
EOF
else
cat > "$ROOT/env.sh" <<EOF
# generated by vs-labs-linux install.sh (system Wine)
export VSLAB_ROOT=$ROOT
export WINEPREFIX=$ROOT/wineprefix
export WINEDEBUG=-all
export WINEARCH=win64
export DISPLAY=
EOF
fi
. "$ROOT/env.sh"

# ---------------------------------------------------------------- vslab on PATH
mkdir -p "$HOME/.local/bin"
ln -sf "$HERE/bin/vslab" "$HOME/.local/bin/vslab"
grep -q "VSLAB_ROOT" "$HOME/.profile" 2>/dev/null || echo "export VSLAB_ROOT=\"$ROOT\"" >> "$HOME/.profile"
export VSLAB_ROOT="$ROOT"
case ":$PATH:" in *":$HOME/.local/bin:"*) ;; *) echo "note: add \$HOME/.local/bin to your PATH";; esac

[ "$DO_MSVC" = yes ] || { echo "skipping MSVC (--no-msvc)"; exit 0; }

# ---------------------------------------------------------------- 2. msvc-wine
say "msvc-wine (open source downloader/installer for Microsoft's tools)"
[ -d "$ROOT/msvc-wine/.git" ] || git clone --depth 1 https://github.com/mstorsjo/msvc-wine "$ROOT/msvc-wine"
[ -d "$ROOT/wineprefix" ] || { echo "creating Wine prefix"; wineboot -i >/dev/null 2>&1 || true; }

# ---------------------------------------------------------------- 3. license
if [ -d "$ROOT/msvc/VC/Tools/MSVC" ]; then
  echo "MSVC already installed in $ROOT/msvc"
else
  say "Microsoft license"
  cat <<EOF
The C++ compiler, linker, libraries and Windows SDK belong to Microsoft. They are downloaded from Microsoft's
servers to YOUR computer and are covered by the Visual Studio license:

    https://go.microsoft.com/fwlink/?LinkId=2327714

Read it. If you do not accept it, answer anything but "yes" and nothing is downloaded.
EOF
  [ -r /dev/tty ] || { echo "no terminal: run this installer in an interactive terminal so you can answer."; exit 1; }
  read -r -p 'Do you accept the Visual Studio license? Type yes to accept: ' ans </dev/tty
  [ "$ans" = yes ] || { echo "License not accepted. Stopping."; exit 1; }
  printf 'Visual Studio license (https://go.microsoft.com/fwlink/?LinkId=2327714) accepted by user %s on %s by typing "yes" in install.sh\n' \
     "$(id -un)" "$(date -Is)" >> "$ROOT/LICENSE-ACCEPTED.txt"

  # ------------------------------------------------------------ 4. install
  say "Downloading MSVC + Windows SDK (about 2 to 3 GB download, about 3 GB on disk). Disk free:"; df -h "$ROOT" | tail -1
  args=(--dest "$ROOT/msvc" --cache "$ROOT/cache" --accept-license)
  [ -n "$MSVC_VERSION" ] && args+=(--msvc-version "$MSVC_VERSION")
  [ -n "$SDK_VERSION" ] && args+=(--sdk-version "$SDK_VERSION")
  [ "$MSBUILD" = yes ] && args+=(--with-msbuild yes) || args+=(--with-msbuild no)
  ( cd "$ROOT/msvc-wine" && python3 vsdownload.py "${args[@]}" && ./install.sh "$ROOT/msvc" )
  rm -rf "$ROOT/cache"
fi

say "Done"
echo "MSVC: $(ls "$ROOT/msvc/VC/Tools/MSVC")   SDK: $(ls "$ROOT/msvc/Windows Kits/10/Include" | tr '\n' ' ')"
echo "Try:  vslab doctor   then   vslab new LabHello_YourName"
